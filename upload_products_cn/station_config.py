def normalize_header(name):
    """把任意表头做规范化（去空格、统一全/半角括号），用于精确匹配。"""
    if name is None:
        return ""
    s = str(name).strip()
    s = s.replace("（", "(").replace("）", ")")
    return s


def resolve_source_col(target_canon, source_headers):
    """在源表头里找 target_canon 对应的列索引（精确 + 同义词）。

    返回列索引（0-based）或 None。
    """
    norm_src = {normalize_header(h): i for i, h in enumerate(source_headers)}
    # 1) 精确
    if target_canon in norm_src:
        return norm_src[target_canon]
    # 2) 同义词
    for alias in ALIASES.get(target_canon, []):
        if alias in norm_src:
            return norm_src[alias]
    # 3) 反向：源表头本身可能是同义词之一
    for i, h in enumerate(source_headers):
        nh = normalize_header(h)
        if nh == target_canon:
            return i
        if nh in ALIASES.get(target_canon, []):
            return i
    return None
